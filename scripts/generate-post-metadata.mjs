import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';

const POSTS_DIR = path.join(process.cwd(), 'src', 'posts');
const METADATA_OUT = path.join(process.cwd(), 'src', 'post-metadata.ts');
const COMPONENTS_OUT = path.join(POSTS_DIR, 'components.ts');
const SLUGS_FILE = path.join(process.cwd(), 'src', 'post-slugs.ts');

const METADATA_KEYS = [
  'title',
  'slug',
  'tags',
  'description',
  'cover',
  'published',
  'shortCodes',
  'bskyThreadId',
  'updated',
];
const REQUIRED_KEYS = ['title', 'slug', 'description', 'cover', 'published'];

const BANNER = `// GENERATED BY scripts/generate-post-metadata.mjs - DO NOT EDIT BY HAND.\n// Run \`pnpm metadata\` after adding or editing a post.\n`;

function extractMetadata(filePath, source) {
  const sourceFile = ts.createSourceFile(
    filePath,
    source,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TSX,
  );

  const metadata = {};
  let draft = false;
  let draftIsValid = true;
  let sawDraft = false;

  for (const statement of sourceFile.statements) {
    if (!ts.isVariableStatement(statement)) {
      continue;
    }

    const isExported = statement.modifiers?.some(
      (modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword,
    );

    if (!isExported) {
      continue;
    }

    for (const declaration of statement.declarationList.declarations) {
      if (!ts.isIdentifier(declaration.name) || !declaration.initializer) {
        continue;
      }

      const name = declaration.name.text;

      if (name === 'draft' && !sawDraft) {
        sawDraft = true;
        const kind = declaration.initializer.kind;
        if (kind === ts.SyntaxKind.TrueKeyword) {
          draft = true;
        } else if (kind !== ts.SyntaxKind.FalseKeyword) {
          draftIsValid = false;
        }
      }

      if (METADATA_KEYS.includes(name) && !(name in metadata)) {
        metadata[name] = declaration.initializer.getText(sourceFile);
      }
    }
  }

  return { metadata, draft, draftIsValid, sawDraft };
}

const RAW_DRAFT_PATTERN = /^export const draft\s*=/m;

const checkOnly = process.argv.includes('--check');

function readIfExists(file) {
  return fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
}

function readGeneratedSlugs() {
  if (!fs.existsSync(SLUGS_FILE)) {
    return null;
  }
  const matches = fs.readFileSync(SLUGS_FILE, 'utf8').match(/'[^']*'/g);
  return matches ? matches.map((value) => value.slice(1, -1)) : [];
}

function fail(lines) {
  for (const line of lines) {
    console.error(line);
  }
  process.exit(1);
}

function main() {
  const files = fs
    .readdirSync(POSTS_DIR)
    .filter((file) => file.endsWith('.mdx') && file !== 'template.mdx')
    .sort();

  const posts = [];
  const drafts = [];
  const problems = [];

  for (const file of files) {
    const filePath = path.join(POSTS_DIR, file);
    const source = fs.readFileSync(filePath, 'utf8');
    const { metadata, draft, draftIsValid, sawDraft } = extractMetadata(
      filePath,
      source,
    );

    if (!sawDraft && RAW_DRAFT_PATTERN.test(source)) {
      problems.push(
        `${file}: \`export const draft\` was found but is not in the metadata export block at the top of the file, so it would be ignored. Move it up with the other exports.`,
      );
      continue;
    }

    if (!draftIsValid) {
      problems.push(
        `${file}: \`export const draft\` must be the literal \`true\` or \`false\``,
      );
      continue;
    }

    if (draft) {
      drafts.push(file);
      continue;
    }

    const missing = REQUIRED_KEYS.filter((key) => !(key in metadata));

    if (missing.length) {
      problems.push(`${file} is missing: ${missing.join(', ')}`);
      continue;
    }

    posts.push({ file, metadata });
  }

  if (problems.length) {
    fail([
      'Could not read metadata from every post:',
      ...problems.map((problem) => `  - ${problem}`),
    ]);
  }

  const seen = new Map();
  for (const { file, metadata } of posts) {
    const slug = metadata.slug;
    if (seen.has(slug)) {
      fail([
        `Duplicate slug ${slug} in ${file} and ${seen.get(slug)}. Slugs must be unique.`,
      ]);
    }
    seen.set(slug, file);
  }

  const generatedSlugs = readGeneratedSlugs();
  if (generatedSlugs) {
    const published = new Set(
      posts.map(({ metadata }) => metadata.slug.replace(/^['"]|['"]$/g, '')),
    );
    const fromGo = new Set(generatedSlugs);
    const onlyGo = [...fromGo].filter((slug) => !published.has(slug));
    const onlyHere = [...published].filter((slug) => !fromGo.has(slug));

    if (onlyGo.length || onlyHere.length) {
      fail([
        'post-slugs.ts disagrees with the posts found here, so postCount and',
        'the slug list would not match the generated metadata.',
        ...onlyGo.map((slug) => `  - only in post-slugs.ts: ${slug}`),
        ...onlyHere.map((slug) => `  - only in post-metadata.ts: ${slug}`),
        'Both generators must skip the same drafts. Re-run `pnpm metadata`.',
      ]);
    }
  }

  const metadataEntries = posts
    .map(({ metadata }) => {
      const fields = METADATA_KEYS.filter((key) => key in metadata)
        .map((key) => `    ${key}: ${metadata[key]},`)
        .join('\n');
      return `  {\n${fields}\n  },`;
    })
    .join('\n');

  const metadataContent = `${BANNER}\nimport { PostMetadata } from '@/types/post';\n\nexport const postMetadata: PostMetadata[] = [\n${metadataEntries}\n];\n\nexport default postMetadata;\n`;

  const componentEntries = posts
    .map(({ file, metadata }) => {
      const slug = JSON.stringify(metadata.slug.replace(/^['"]|['"]$/g, ''));
      return `  ${slug}: () => import('./${file}'),`;
    })
    .join('\n');

  const componentsContent = `${BANNER}\nimport { PostModule } from '@/types/post';\n\nexport const postComponents: Record<string, () => Promise<PostModule>> = {\n${componentEntries}\n};\n\nexport default postComponents;\n`;

  if (checkOnly) {
    const stale = [];
    if (readIfExists(METADATA_OUT) !== metadataContent) {
      stale.push('src/post-metadata.ts');
    }
    if (readIfExists(COMPONENTS_OUT) !== componentsContent) {
      stale.push('src/posts/components.ts');
    }

    if (stale.length) {
      fail([
        'Generated post files are out of date:',
        ...stale.map((file) => `  - ${file}`),
        '',
        'A post was added, edited, or marked `draft` without regenerating.',
        'Run `pnpm metadata` and commit the result.',
      ]);
    }

    console.log(
      `Generated post files are up to date (${posts.length} posts, ${drafts.length} draft${drafts.length === 1 ? '' : 's'}).`,
    );
    return;
  }

  fs.writeFileSync(METADATA_OUT, metadataContent);
  fs.writeFileSync(COMPONENTS_OUT, componentsContent);

  const draftNote = drafts.length
    ? ` (skipped ${drafts.length} draft${drafts.length === 1 ? '' : 's'}: ${drafts.join(', ')})`
    : '';

  console.log(
    `Wrote metadata for ${posts.length} posts to src/post-metadata.ts and src/posts/components.ts${draftNote}`,
  );
}

main();
